/**
 * L-12 · THE PLAY DATA SAFETY DECLARATIONS, GENERATED FROM THE NOTICE.
 *
 * Google Play requires the Data Safety form to match what the app actually
 * does AND what the privacy policy says. The usual way that promise breaks is
 * not deceit: it is three artifacts maintained by hand, one of which is a web
 * form somebody filled in six months ago. The app changes, the policy is
 * updated, and the form keeps declaring what was true in March.
 *
 * AD-005 promised a check for exactly this. So the declarations are DERIVED
 * from the itemised notice the API serves - the same object the app renders on
 * the consent screen - and `check:generated` fails if this file is hand-edited
 * away from it. A new collected item cannot reach the app without appearing
 * here.
 *
 * WHAT IS DERIVED AND WHAT IS A JUDGEMENT, KEPT SEPARATE. The items, what each
 * collects, why, whether it is required and its retention all come from the
 * notice. Mapping "mobile number" onto Play's own taxonomy is a JUDGEMENT -
 * their category names are theirs, they change, and a wrong guess is a wrong
 * declaration. Each mapping therefore carries its reasoning, and the document
 * says plainly that the final labels must be confirmed against the Console
 * (H7) rather than trusted from here.
 *
 * NOTHING IS SHARED, and that is the one declaration this build can make
 * without hedging: there is no analytics SDK, no advertising SDK, no third
 * party receiving personal data. `check:licences` walks the shipped closure
 * and `check:push` watches for the one that would change it.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { NOTICE } from '../apps/api/src/dpdp/routes.ts';
import { DELETION_GRACE_DAYS } from '../packages/values/src/index.ts';

/**
 * How each thing the notice says we collect maps onto Play's taxonomy.
 *
 * THE KEY IS THE EXACT STRING FROM THE NOTICE, so a collected item that is
 * renamed or added has no mapping and this generator fails rather than
 * quietly omitting it from the declaration. That failure is the point: an
 * undeclared data type is the defect Play rejects a submission for.
 */
const TAXONOMY = {
  'mobile number': {
    type: 'Personal info · Phone number',
    why: 'Account management, App functionality',
    note: 'It is the account identifier and the sign-in channel.',
  },
  'shop name': {
    type: 'Personal info · Other info',
    why: 'App functionality',
    note: 'A shop name can identify a sole trader, so it is treated as personal info rather than as a label.',
  },
  'the entries you type': {
    type: 'Financial info · Other financial info',
    why: 'App functionality',
    note: 'Takings, purchases and expenses. Not a payment instrument and not a transaction with us - no money moves through SWAFTO.',
  },
  'customer and supplier names you enter': {
    type: 'Personal info · Names',
    why: 'App functionality',
    note: "Third-party personal data, recorded on the shopkeeper's instruction. AD-006: he is the Fiduciary for it and we are the Processor.",
  },
  'device model': {
    type: 'App info and performance · Diagnostics',
    why: 'Crash reporting, Diagnostics',
    note: 'Optional, and only when crash reporting is switched on.',
  },
  'app version': {
    type: 'App info and performance · Diagnostics',
    why: 'Crash reporting, Diagnostics',
    note: 'Optional, and only when crash reporting is switched on.',
  },
  'the point in the app where it stopped': {
    type: 'App info and performance · Crash logs',
    why: 'Crash reporting',
    note: 'Never carries an amount, a customer name or a phone number. B36 is the check.',
  },
};

const rows = [];
const unmapped = [];

for (const item of NOTICE.items) {
  for (const collected of item.collects) {
    const mapped = TAXONOMY[collected];
    if (!mapped) {
      unmapped.push({ purpose: item.purpose, collected });
      continue;
    }
    rows.push({
      purpose: item.purpose,
      required: item.required,
      collected,
      ...mapped,
      retention: item.retention,
    });
  }
}

if (unmapped.length) {
  console.error('\nUNDECLARABLE DATA (' + unmapped.length + '):');
  for (const u of unmapped) {
    console.error('  x    "' + u.collected + '" (' + u.purpose + ') has no Play mapping');
  }
  console.error(
    '\nThe notice says this is collected and nothing here says how to declare it.\n' +
      'An undeclared data type is what a Play submission is rejected for - and the\n' +
      'honest failure is here rather than a quiet omission from the form. Add the\n' +
      'mapping to TAXONOMY in tools/gen-data-safety.mjs, with its reasoning.',
  );
  process.exit(1);
}

const tick = (b) => (b ? 'Yes' : 'No');

const doc = `<!-- GENERATED by tools/gen-data-safety.mjs from the itemised notice the API
     serves (apps/api/src/dpdp/routes.ts). Do not edit by hand: check:generated
     regenerates it and fails on any difference, which is what stops the form
     and the app from drifting apart. -->

# PLAY DATA SAFETY DECLARATIONS

**L-12.** What to enter in the Play Console's Data Safety form, derived from the same
notice the app shows before an account is created.

> **The category labels are a JUDGEMENT and must be confirmed in the Console (H7).**
> Google's taxonomy is theirs and it changes. Everything else on this page - what is
> collected, why, whether it is required, how long it is kept - is derived from the
> notice and cannot drift from it.

## The summary answers

| Question | Answer | Why |
|---|---|---|
| Does your app collect or share any of the required user data types? | **Yes** | ${rows.length} items, listed below |
| Is all of the user data collected by your app encrypted in transit? | **Yes** | TLS 1.3 only; cleartext is refused |
| Do you provide a way for users to request that their data be deleted? | **Yes** | In the app, and at \`swafto.app/delete-account\` with the app uninstalled |
| Is any data shared with third parties? | **No** | No analytics SDK, no advertising SDK, no third party receives personal data |
| Is any data processed ephemerally? | **No** | What is collected is stored, and the retention column says for how long |
| Is data collection required to use the app? | **Partly** | Only the account-and-ledger purpose is required; the other two are refusable |

## The data types

| Play data type | Collected | Shared | Required | Purpose | From the notice |
|---|---|---|---|---|---|
${rows
  .map(
    (r) =>
      `| ${r.type} | Yes | No | ${tick(r.required)} | ${r.why} | ${r.purpose} - "${r.collected}" |`,
  )
  .join('\n')}

## Why each mapping was chosen

${rows.map((r) => `- **${r.type}** - ${r.note}`).join('\n')}

## Retention, as declared

${NOTICE.items
  .map((i) => `- **${i.purpose}** (${i.required ? 'required' : 'optional'}): ${i.retention}`)
  .join('\n')}

Deletion takes effect after a **${DELETION_GRACE_DAYS}-day grace period** during which
signing in cancels it. After that, encrypted backups rotate out within 90 days and are
never restored.

## The URLs the form asks for

| Field | Value |
|---|---|
| Privacy policy | \`https://swafto.app/privacy\` (\`apps/web/legal/privacy.html\`) |
| Account deletion | \`https://swafto.app/delete-account\` (\`apps/web/delete-account/index.html\`) |

Both must be **live** before submission. Publishing them is H5; the pages exist.

## What this page deliberately does not claim

- That the Console has been filled in. It has not; that needs an account (H7).
- That Google's category names are exactly these. Confirm them against the form.
- That the policy has been reviewed by counsel. It has not (H9), and it says so on
  its own first screen.
`;

writeFileSync('docs/handover/DATA-SAFETY.md', doc);

console.log('  notice version         : ' + NOTICE.version);
console.log('  purposes               : ' + NOTICE.items.length);
console.log('  declarable data types  : ' + rows.length + ', all mapped');
console.log('  shared with anybody    : no');
console.log('\nwrote docs/handover/DATA-SAFETY.md');

/* A reader of the policy must find the same items. */
const policy = readFileSync('apps/web/legal/privacy.html', 'utf8');
const missing = rows.filter((r) => !policy.includes(r.collected));
if (missing.length) {
  console.error('\nTHE POLICY DOES NOT LIST (' + missing.length + '):');
  for (const m of missing) console.error('  x    ' + m.collected);
  console.error(
    '\nAD-005: the policy and the Data Safety declarations must agree on every\n' +
      'collected item. They do not. Fix the policy - it is the document a person\n' +
      'reads, and the notice is what the software does.',
  );
  process.exit(1);
}
