// Emit both dialects from the single spec, so the .sql files in migrations/ are
// always generated and never hand-edited. CI re-runs this and fails on a diff.
import { writeFileSync, mkdirSync } from 'node:fs';
import { migrationUp, migrationDown, renderSQL } from '../packages/schema/src/spec.ts';

mkdirSync('packages/schema/migrations', { recursive: true });
for (const dialect of ['sqlite', 'postgres']) {
  const header = `-- GENERATED by tools/emit-sql.mjs from packages/schema/src/spec.ts\n-- DO NOT EDIT BY HAND. Dialect: ${dialect}\n\n`;
  writeFileSync(`packages/schema/migrations/0001_init.${dialect}.up.sql`,   header + renderSQL(migrationUp(dialect)));
  writeFileSync(`packages/schema/migrations/0001_init.${dialect}.down.sql`, header + renderSQL(migrationDown(dialect)));
  console.log(`emitted ${dialect}: ${migrationUp(dialect).length} up / ${migrationDown(dialect).length} down statements`);
}
