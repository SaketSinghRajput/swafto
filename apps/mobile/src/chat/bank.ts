/**
 * THE INTENT BANK - what the Ask matcher knows, as data (R3 §2).
 *
 * Per intent: phrasings in English, Hindi in Devanagari, romanised Hindi
 * (Hinglish), Odia in its own script and romanised Odia, because shopkeepers
 * type the way they speak. The matcher (match.ts) scores a question against
 * these and nothing else.
 *
 * THE ODIA AND HINDI PHRASINGS ARE DRAFTS written on this build, not phrasings
 * collected from shopkeepers. R3's acceptance step - at least 300 real phrasings
 * per language from pilot shops - has not happened (H13 covers the copy; the
 * corpus is the same kind of gap). A misroute on real phrasing is fixed HERE,
 * by adding the phrasing, never by lowering the floor in match.ts.
 *
 * RULES FOR A PHRASE. No party names (a name is a slot and is matched against
 * the shop's own list). Periods, months and "30 days" may appear - they are
 * lifted out before scoring, exactly as they are from a question. No stock or
 * inventory question is answered with a figure, ever: `noStock` exists so that
 * question gets an honest "this app does not keep stock" instead of being
 * routed to whatever it happens to resemble.
 */

